  function applyLang(lang) {
    const dict = STRINGS[lang] || STRINGS.en;

    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      if (dict[key] !== undefined) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.dataset.i18nHtml;
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.dispatchEvent(new CustomEvent('s21-lang-changed', { detail: { lang } }));

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.dataset.i18nPlaceholder;
      if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
    });

    // Language toggle buttons: show the language you'd switch TO.
    // The desktop button is plain text (safe to set via textContent); the
    // mobile button has an icon + a labeled span, so only that span's text
    // is updated to avoid wiping out the icon.
    const toTongue = lang === 'en' ? { code: 'sw', short: 'SW', name: dict.ob_lang_kiswahili || 'Kiswahili' }
                                    : { code: 'en', short: 'EN', name: 'English' };
    document.querySelectorAll('[data-lang-toggle]').forEach((btn) => {
      const label = btn.querySelector('[data-lang-toggle-label]');
      if (label) label.textContent = toTongue.name;
      else btn.textContent = toTongue.short;
    });
  }

  function getSavedLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      return saved || 'sw';
    } catch (e) { return 'sw'; }
  }

  document.addEventListener('DOMContentLoaded', () => {
    applyLang(getSavedLang());

    document.querySelectorAll('[data-lang-toggle]').forEach((btn) => {
      btn.addEventListener('click', () => {
        const next = getSavedLang() === 'en' ? 'sw' : 'en';
        try { localStorage.setItem(STORAGE_KEY, next); } catch (e) { /* ignore */ }
        applyLang(next);
      });
    });
  });

  // Exposed so onboarding.html can re-apply translations live as the
  // visitor picks a language on step 1, before the choice is "saved".
  window.S21_applyLang = applyLang;

  // Exposed so other scripts (games.js, main.js, etc.) can look up a
  // translated string for the *currently active* language when they set
  // text at runtime (e.g. quiz feedback, form status messages).
  window.S21_t = function (key) {
    const dict = STRINGS[getSavedLang()] || STRINGS.en;
    return dict[key] !== undefined ? dict[key] : (STRINGS.en[key] || key);
  };
